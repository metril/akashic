"""Rewrite ``tests/openapi_allowlist.py`` from the current contract violations.

Run after *fixing* violations (to drop stale entries). Do not use it to
silence new ones: the ratchet exists so the list only shrinks.
"""
from __future__ import annotations

import os
import sys
import tempfile
from pathlib import Path

API = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(API))
os.environ.setdefault("SECRET_KEY_FILE", os.path.join(tempfile.mkdtemp(prefix="akashic-allow-"), "secret.key"))


def main() -> None:
    from akashic.main import create_app
    from tests.test_openapi_contract import CATEGORIES, collect_violations

    app = create_app()
    found = collect_violations(app, app.openapi())
    lines = [
        '"""Ratchet for tests/test_openapi_contract.py: known violations, shrink-only.',
        "",
        "Generated by api/scripts/regen_openapi_allowlist.py (`make openapi-allowlist`).",
        '"""',
        "",
        "ALLOWLIST: dict[str, frozenset[str]] = {",
    ]
    for cat in CATEGORIES:
        lines.append(f'    "{cat}": frozenset({{')
        lines.extend(f"        {entry!r}," for entry in sorted(found[cat]))
        lines.append("    }),")
    lines.append("}")
    (API / "tests" / "openapi_allowlist.py").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print({c: len(found[c]) for c in CATEGORIES})


if __name__ == "__main__":
    main()
